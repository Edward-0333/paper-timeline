const { _electron: electron } = require('playwright-core');
const assert = require('node:assert/strict');
const { readdirSync, mkdirSync, writeFileSync } = require('node:fs');
const path = require('node:path');
const env = { ...process.env, PAPER_TIMELINE_DATA: path.resolve('.test-data', `desktop-${Date.now()}`) };
delete env.ELECTRON_RUN_AS_NODE;
(async () => {
  mkdirSync('test-results', { recursive: true });
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], env, cwd: process.cwd(), timeout: 45000 });
  try {
    const page = await app.firstWindow();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.getByRole('button', { name: '导入 PDF', exact: true }).waitFor();
    await page.waitForFunction(() => !document.querySelector('.primary-button').disabled);
    assert.equal(await page.locator('.paper-row').count(), 0);
    await page.screenshot({ path: 'test-results/desktop-empty.png' });
    const files = readdirSync('../pdf').filter(f => /\.pdf$/i.test(f)).map(f => path.resolve('../pdf', f));
    await app.evaluate(({ dialog }, files) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: files }); }, files);
    await page.getByRole('button', { name: '导入 PDF', exact: true }).click();
    await page.waitForFunction(n => document.querySelectorAll('.paper-row').length === n, files.length);
    await page.screenshot({ path: 'test-results/desktop-processing.png' });
    await page.waitForFunction(n => { const rows = [...document.querySelectorAll('.paper-row')]; return rows.length === n && rows.every(row => !row.querySelector('.status-queued, .status-extracting, .status-searching')); }, files.length, { timeout: 240000 });
    const library = await page.evaluate(() => window.paperApi.getLibrary());
    console.log('DESKTOP RESULTS', JSON.stringify(library.papers.map(({ title, status, source, authors, year, message }) => ({ title, status, source, authorCount: authors.length, year, message })), null, 2));
    writeFileSync('test-results/desktop-report.json', JSON.stringify({ storagePath: library.storagePath, papers: library.papers.map(({ thumbnail, ...p }) => p) }, null, 2));
    assert.equal(library.papers.filter(p => p.status === 'matched').length, files.length, 'All sample papers should resolve online');
    // This exercises the file bridge used by drag-and-drop, with an actual disk-backed File.
    await page.getByLabel('选择 PDF 文件').setInputFiles(files[0]);
    await page.getByRole('alert').filter({ hasText: '重复文件已跳过' }).waitFor();
    assert.equal(await page.locator('.paper-row').count(), files.length);
    await page.getByLabel('搜索文献').fill('Driving on Registers');
    assert.equal(await page.locator('.paper-row').count(), 1);
    await page.locator('.paper-row').click();
    await page.getByLabel('清空搜索').click();
    await page.getByLabel('更多操作').click();
    await page.getByLabel('编辑元数据').click();
    await page.getByLabel('标题', { exact: true }).fill('Driving on Registers — checked');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('.detail-title').textContent(), 'Driving on Registers — checked');
    await page.getByLabel('更多操作').click();
    await page.getByLabel('编辑元数据').click();
    await page.getByLabel('标题', { exact: true }).fill('Driving on Registers');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByLabel('更多操作').click();
    await page.getByRole('button', { name: '重新检索' }).click();
    await page.waitForFunction(() => !!document.querySelector('.detail-panel .status-queued, .detail-panel .status-extracting, .detail-panel .status-searching'));
    await page.waitForFunction(() => document.querySelector('.match-notice')?.textContent?.includes('arXiv ·'), undefined, { timeout: 60000 });
    await page.reload();
    await page.waitForFunction(n => document.querySelectorAll('.paper-row').length === n, files.length);
    await page.locator('.paper-row').filter({ hasText: 'Driving on Registers' }).click();
    const closeToast = page.getByRole('button', { name: '关闭通知' }); if (await closeToast.count()) await closeToast.click();
    await page.screenshot({ path: 'test-results/desktop-library.png' });
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1100, 800));
    await page.screenshot({ path: 'test-results/desktop-compact.png' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
    assert.deepEqual(errors, []);
    console.log('PASS: native import, worker parsing, online metadata, duplicate handling, search, edit, retry, persistence, compact layout and isolation.');
  } finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
