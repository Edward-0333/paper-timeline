const { _electron: electron } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = process.cwd();
const report = JSON.parse(fs.readFileSync('test-results/desktop-report.json', 'utf8'));
const data = path.resolve('.test-data', `folders-ui-${Date.now()}`);
fs.mkdirSync(data, { recursive: true });
fs.cpSync(report.storagePath, path.join(data, 'library'), { recursive: true });
const env = { ...process.env, PAPER_TIMELINE_DATA: data }; delete env.ELECTRON_RUN_AS_NODE;

(async () => {
  const app = await electron.launch({ executablePath: require('electron'), args: ['.'], env, cwd: root });
  try {
    const page = await app.firstWindow(), errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.waitForFunction(() => document.querySelectorAll('.paper-row').length === 6);
    const sidebar = page.getByRole('navigation', { name: '文献文件夹' });
    const all = () => sidebar.getByRole('button', { name: /^全部文献/ }).click();
    const folder = name => sidebar.locator('.folder-row .folder-item').filter({ hasText: name });
    const create = async name => {
      await page.getByRole('button', { name: '新建文件夹', exact: true }).click();
      await page.getByLabel('文件夹名称').fill(name);
      await page.getByRole('button', { name: '保存文件夹', exact: true }).click();
      await page.getByRole('dialog').waitFor({ state: 'hidden' });
    };
    await create('世界模型');
    await page.getByRole('heading', { name: '文件夹中还没有论文' }).waitFor();
    assert.equal(await folder('世界模型').getAttribute('aria-current'), 'page');
    let state = await page.evaluate(() => window.paperApi.getLibrary());
    const world = state.folders.find(f => f.name === '世界模型'); assert.ok(world);
    await all();
    await page.locator('.paper-row').filter({ hasText: 'End-to-End Driving with Online Trajectory' }).click();
    await page.getByLabel('所属文件夹', { exact: true }).selectOption(world.id);
    await page.waitForFunction(() => document.querySelector('.folder-row .folder-item small')?.textContent === '1');
    await folder('世界模型').click();
    assert.equal(await page.locator('.paper-row').count(), 1);
    assert.match(await page.locator('.detail-title').innerText(), /End-to-End Driving/);
    await page.getByLabel('搜索文献').fill('missing-paper');
    await page.getByRole('heading', { name: '没有匹配的文献' }).waitFor();
    await page.getByLabel('清空搜索').click();
    const switchBox = await page.getByRole('group', { name: '文献视图' }).boundingBox();
    await page.getByRole('button', { name: '时间线', exact: true }).click();
    assert.equal(await page.locator('.timeline-paper').count(), 1);
    const mapSwitch = await page.getByRole('group', { name: '文献视图' }).boundingBox();
    assert.equal(mapSwitch.x, switchBox.x); assert.equal(mapSwitch.y, switchBox.y);
    await page.getByRole('button', { name: '列表', exact: true }).click();
    await page.reload();
    await folder('世界模型').click();
    assert.equal(await page.locator('.paper-row').count(), 1);

    await page.getByLabel('世界模型的文件夹操作').click();
    await page.getByRole('button', { name: '重命名', exact: true }).click();
    await page.getByLabel('文件夹名称').fill('世界模型论文');
    await page.getByRole('button', { name: '保存文件夹', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.equal(await folder('世界模型论文').getAttribute('aria-current'), 'page');
    await create('轨迹规划');
    state = await page.evaluate(() => window.paperApi.getLibrary());
    const planning = state.folders.find(f => f.name === '轨迹规划');
    await all();
    await page.locator('.paper-row').filter({ hasText: 'Driving on Registers' }).click();
    await page.getByLabel('所属文件夹').selectOption(planning.id);
    await page.waitForFunction(() => [...document.querySelectorAll('.folder-row')].some(el => el.textContent.includes('轨迹规划1')));
    await page.getByRole('button', { name: '新建文件夹', exact: true }).click();
    await page.getByLabel('文件夹名称').fill('轨迹规划');
    await page.getByRole('button', { name: '保存文件夹', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: '同名文件夹' }).waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });

    await page.getByRole('button', { name: '标题', exact: true }).click();
    let titles = await page.locator('.table-title span').allTextContents();
    assert.deepEqual(titles, [...titles].sort((a, b) => a.localeCompare(b, 'zh-CN', { numeric: true })));
    await page.getByRole('button', { name: '发表日期', exact: true }).click();
    assert.match(await page.locator('.paper-row').first().innerText(), /2024/);
    await page.getByRole('button', { name: '发表日期', exact: true }).click();
    assert.match(await page.locator('.paper-row').first().innerText(), /2026/);
    await page.locator('.paper-row').first().click();
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.locator('.detail-title').innerText(), await page.locator('.paper-row.selected .table-title span').innerText());
    await app.evaluate(({ shell }) => { shell.openPath = async file => { globalThis.lastOpenedPdf = file; return ''; }; });
    await page.locator('.paper-row').first().dblclick();
    assert.match(await app.evaluate(() => globalThis.lastOpenedPdf), /papers.*original\.pdf$/);
    await page.locator('.paper-row').filter({ hasText: 'End-to-End Driving with Online Trajectory' }).click();
    await page.screenshot({ path: 'test-results/desktop-three-columns.png' });
    const boxes = await Promise.all([sidebar, page.locator('.paper-list'), page.locator('.detail-panel')].map(el => el.boundingBox()));
    assert.ok(boxes[0].x + boxes[0].width <= boxes[1].x + 1);
    assert.ok(boxes[1].x + boxes[1].width <= boxes[2].x + 1);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1050, 700));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: 'test-results/desktop-three-columns-compact.png' });
    await folder('轨迹规划').click();
    await page.getByLabel('轨迹规划的文件夹操作').click();
    await page.getByRole('button', { name: '删除文件夹', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: '删除文件夹', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.equal(await folder('轨迹规划').count(), 0);
    state = await page.evaluate(() => window.paperApi.getLibrary());
    assert.equal(state.papers.length, 6);
    assert.equal(state.papers.find(p => p.title === 'Driving on Registers').folderId, null);
    assert.ok(state.papers.every(p => fs.existsSync(path.join(state.storagePath, 'papers', p.storageFolder, 'original.pdf'))));
    assert.deepEqual(errors, []);
  } finally { await app.close(); }

  const imported = await electron.launch({ executablePath: require('electron'), args: ['.'], env: { ...env, PAPER_TIMELINE_DATA: data + '-import' }, cwd: root });
  try {
    const page = await imported.firstWindow();
    await page.getByRole('heading', { name: '导入你的第一篇论文' }).waitFor();
    await page.getByRole('button', { name: '新建文件夹', exact: true }).click();
    await page.getByLabel('文件夹名称').fill('导入目标');
    await page.getByRole('button', { name: '保存文件夹', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('.folder-row .folder-item').filter({ hasText: '导入目标' }).getAttribute('aria-current'), 'page');
    const filename = fs.readdirSync('../pdf').find(f => f.includes('Driving on Registers'));
    const file = path.resolve('../pdf', filename);
    await imported.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, file);
    await page.getByRole('button', { name: '导入 PDF', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.paper-row').length === 1 && !document.querySelector('.paper-row .status-queued, .paper-row .status-extracting, .paper-row .status-searching'), undefined, { timeout: 90000 });
    const state = await page.evaluate(() => window.paperApi.getLibrary());
    assert.equal(state.papers.length, 1); assert.equal(state.papers[0].folderId, state.folders[0].id);
    assert.equal(state.folders[0].name, '导入目标'); assert.equal(state.papers[0].status, 'matched');
    assert.equal(await page.getByLabel('所属文件夹').inputValue(), state.folders[0].id);
  } finally { await imported.close(); }
  console.log('PASS: three-column layout, folder create/rename/delete, classification, reload persistence, scoped timeline/search, sorting, keyboard selection, opening PDFs, compact layout, duplicate names and import into a folder.');
})().catch(error => { console.error(error); process.exitCode = 1; });
